// Phone + fake client flow against the mock League client (see run.sh).
const { chromium } = require('playwright');
const fs = require('fs');
const OUT = process.env.OUT || '.';
const PIN = process.env.PIN;
const shot = (p, n) => p.screenshot({ path: `${OUT}/${n}.png` });
(async () => {
  const browser = await chromium.launch();
  const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  const errors = [];
  phone.on('pageerror', e => errors.push('pageerror: ' + e.message));
  phone.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  await fetch('http://127.0.0.1:29999/mock/goto?state=none');
  await phone.goto('http://127.0.0.1:8787/');
  await phone.waitForSelector('.pin-input');
  await shot(phone, '01-pair');
  await phone.fill('.pin-input', PIN);
  await phone.click('text=Connecter');
  await phone.waitForSelector('text=Choisis un mode de jeu');
  await phone.waitForSelector('.mode');
  await shot(phone, '02-modes');
  await phone.click('.mode:has-text("Classée Solo/Duo")');
  await phone.waitForSelector('text=Trouver une partie');
  await shot(phone, '03-lobby');
  await phone.click('.chip:has-text("Jungle")');
  await phone.waitForTimeout(300);
  // Invites and lobby management
  await phone.click('text=+ Inviter des amis');
  await phone.waitForSelector('.friend:has-text("Ami Dispo")');
  await phone.click('.friend:has-text("Ami Dispo") button');
  await phone.fill('input[placeholder^="Riot ID"]', 'Ami Absent#EUW');
  await phone.click('form button:has-text("Inviter")');
  await phone.waitForTimeout(400);
  await shot(phone, '03b-invite');
  await phone.click('.sheet button:has-text("Fermer")');
  await phone.waitForSelector('.member:has-text("Ami Dispo")', { timeout: 8000 });
  await phone.waitForSelector('.member:has-text("Ami Absent")', { timeout: 8000 });
  await phone.click('.member:has-text("Coéquipier") .icon-btn');
  await phone.click('text=Autoriser à inviter');
  await phone.waitForSelector('.member:has-text("Coéquipier") .tag:has-text("Invite")');
  await phone.click('.member:has-text("Ami Dispo") .icon-btn');
  await phone.click('.member-actions button:has-text("Exclure")');
  await phone.waitForSelector('.member:has-text("Ami Dispo")', { state: 'detached', timeout: 5000 });
  await shot(phone, '03c-lobby-managed');
  console.log('lobby management OK');
  await phone.click('text=Trouver une partie');
  await phone.waitForSelector('.banner.searching');
  await shot(phone, '04-search');
  await phone.waitForSelector('text=Partie trouvée', { timeout: 10000 });
  await shot(phone, '05-readycheck');
  await phone.click('button.accept');
  await phone.waitForSelector('text=À toi de bannir', { timeout: 10000 });
  await phone.waitForSelector('.champ img');
  await shot(phone, '06-ban');
  await phone.click('.champ:not(:has-text("Ahri")) >> nth=0');
  await phone.waitForSelector('.champ.selected');
  await phone.click('button:has-text("Bannir")');
  await phone.waitForSelector('text=À toi de choisir', { timeout: 15000 });
  await phone.fill('.search', 'ahri');
  await phone.click('.champ:has-text("Ahri")');
  await phone.waitForSelector('.champ.selected');
  await shot(phone, '07-pick');
  await phone.click('button:has-text("Verrouiller")');
  await phone.waitForSelector('.tab:has-text("Skins")', { timeout: 10000 });
  await phone.waitForSelector('.skin img');
  await phone.waitForTimeout(500);
  await shot(phone, '08-skins-noplugin');
  // Owned skin without plugin -> LCU PATCH
  await phone.click('.skin:has-text("Gardienne des étoiles Ahri")');
  await phone.waitForTimeout(600);
  // Fake client + plugin
  const client = await browser.newPage({ viewport: { width: 700, height: 400 } });
  client.on('console', m => console.log('[client]', m.text()));
  await client.goto('http://127.0.0.1:29999/mock/client');
  await client.waitForSelector('.skin-selection-item');
  const plugin = fs.readFileSync(process.env.PLUGIN, 'utf8').replace('__LOLMOBIL_PORT__', '8787');
  await client.addScriptTag({ content: plugin });
  await phone.waitForSelector('.dot.ok:has-text("Plugin")', { timeout: 10000 });
  await phone.waitForTimeout(500);
  await phone.click('.skin:has-text("Pulsefire Ahri")');
  await client.waitForFunction(() => document.querySelector('.skin-name-text').textContent === 'Pulsefire Ahri', null, { timeout: 8000 });
  await phone.waitForSelector('.rose-line:has-text("Pulsefire Ahri")', { timeout: 8000 });
  await phone.waitForTimeout(800);
  console.log('client shows:', await client.textContent('.skin-name-text'), '| fake Rose:', await client.textContent('#rose'));
  await shot(phone, '09-skins-rose');
  await client.screenshot({ path: `${OUT}/09b-client.png` });
  // Chromas on Lune de sang (unowned, has chromas)
  await phone.click('.skin:has-text("PROJET : Ahri")');
  await client.waitForFunction(() => document.querySelector('.skin-name-text').textContent === 'PROJET : Ahri', null, { timeout: 8000 });
  await phone.waitForSelector('.chroma');
  await phone.click('.chroma >> nth=1');
  await phone.waitForSelector('.chroma.active', { timeout: 5000 });
  await shot(phone, '10-chroma');
  // Adjacent-only carousel
  await client.goto('http://127.0.0.1:29999/mock/client?adjacent');
  await client.waitForSelector('.skin-selection-item');
  await client.addScriptTag({ content: plugin });
  await phone.waitForTimeout(1500);
  await phone.click('.skin:has-text("Hextech Ahri")');
  await client.waitForFunction(() => document.querySelector('.skin-name-text').textContent === 'Hextech Ahri', null, { timeout: 12000 });
  console.log('adjacent mode OK:', await client.textContent('.skin-name-text'));
  await phone.waitForSelector('.rose-line:has-text("Hextech Ahri")', { timeout: 8000 });
  // Runes
  await phone.click('.tab:has-text("Runes")');
  await phone.waitForSelector('.page-summary');
  await phone.waitForSelector('.rec');
  await shot(phone, '11-runes');
  await phone.click('.rec >> nth=0 >> button');
  await phone.waitForTimeout(600);
  await phone.click('.page-item:has-text("Bruiser")');
  await phone.waitForTimeout(400);
  await phone.click('button:has-text("Modifier")');
  await phone.waitForSelector('.rune-editor');
  await shot(phone, '12-rune-editor');
  await phone.click('.rune-editor .style-row >> nth=0 >> .style-btn >> nth=2');
  await phone.click('.perk-row.keystones .perk >> nth=1');
  for (let r = 1; r <= 3; r++) await phone.click(`.rune-editor .perk-row >> nth=${r} >> .perk >> nth=0`);
  await phone.click('.rune-editor .style-row >> nth=1 >> .style-btn >> nth=0');
  await phone.click('.rune-editor .perk-row >> nth=4 >> .perk >> nth=1');
  await phone.click('.rune-editor .perk-row >> nth=5 >> .perk >> nth=2');
  await shot(phone, '13-rune-editor-filled');
  await phone.click('button:has-text("Enregistrer")');
  await phone.waitForSelector('.runes', { timeout: 5000 });
  // Spells
  await phone.click('.tab:has-text("Sorts")');
  await phone.waitForSelector('.spell');
  await phone.click('.spell-slot >> nth=1');
  await phone.click('.spell:has-text("Téléportation")');
  await phone.waitForTimeout(500);
  await shot(phone, '14-spells');
  // ARAM
  await fetch('http://127.0.0.1:29999/mock/goto?state=aram');
  await phone.waitForSelector('text=Banc', { timeout: 8000 });
  await phone.waitForTimeout(800);
  await shot(phone, '15-aram');
  await phone.click('.bench-champ >> nth=0');
  await phone.waitForTimeout(500);
  // In game / end
  await fetch('http://127.0.0.1:29999/mock/goto?state=ingame');
  await phone.waitForSelector('text=Partie en cours');
  await shot(phone, '16-ingame');
  await fetch('http://127.0.0.1:29999/mock/goto?state=endofgame');
  await phone.waitForSelector('text=Rejouer');
  await phone.click('text=Rejouer');
  await phone.waitForSelector('text=Trouver une partie', { timeout: 5000 });
  // Settings + auto accept
  await phone.click('.icon-btn');
  await phone.waitForSelector('.sheet');
  await phone.check('.switch-row input');
  await phone.waitForTimeout(400);
  await shot(phone, '17-settings');
  await phone.click('.sheet button:has-text("Fermer")');
  await phone.click('text=Trouver une partie');
  await phone.waitForSelector('text=Banc', { timeout: 15000 });
  console.log('auto-accept OK');
  console.log('ERRORS:', JSON.stringify(errors, null, 1));
  await browser.close();
  if (errors.length) process.exit(1);
})().catch(e => { console.error('FAILED', e); process.exit(1); });
